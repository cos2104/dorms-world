// 두 브라우저로 방을 만들고 들어가 차례대로 쏘는 시험.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://localhost:5310/world/z/math/angry-cannon';
const browser = await chromium.launch({ executablePath: process.env.PW_CHROME || undefined, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const mk = async (id, sw, tag) => {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  await ctx.addInitScript(([i, s, t]) => localStorage.setItem('dorms-world.me.v1', JSON.stringify({ id: i, swatch: s, tag: t })), [id, sw, tag]);
  const page = await ctx.newPage();
  const errs = []; page.on('pageerror', e => errs.push(String(e)));
  return { page, errs };
};
const A = await mk('aaaaaaaaaaaaaaaa', 'orange', 1);
const B = await mk('bbbbbbbbbbbbbbbb', 'sky', 2);
await A.page.goto(base, { waitUntil: 'networkidle' });
await A.page.getByRole('button', { name: '방 만들기' }).click();
await A.page.waitForSelector('.ac-members li');
const url = new URL(A.page.url());
const code = url.searchParams.get('room');
console.log('room', code);
await B.page.goto(`${base}?room=${code}`, { waitUntil: 'networkidle' });
await B.page.waitForSelector('.ac-members li');
await A.page.waitForFunction(() => document.querySelectorAll('.ac-members li').length >= 2, null, { timeout: 15000 });
console.log('A sees', await A.page.locator('.ac-members li').count(), 'members; B sees', await B.page.locator('.ac-members li').count());
await A.page.getByRole('button', { name: '시작' }).click();
await A.page.waitForTimeout(3000);
const who = async p => p.evaluate(() => document.querySelector('.ac-dock')?.className + ' | ' + (document.querySelector('.ac-dock .ac-title, .ac-dock .ac-step')?.textContent ?? ''));
console.log('A dock:', await who(A.page));
console.log('B dock:', await who(B.page));
// 차례인 쪽을 찾아 상대를 겨눈다(정확한 조준은 게임 안 계산을 빌려 온다).
const shooter = (await A.page.locator('.ac-dock.mode-aim').count()) ? A : B;
const other = shooter === A ? B : A;
await shooter.page.screenshot({ path: `${process.env.HOME}/dorms-world/.shots/mp-turn.png` });
await shooter.page.getByRole('button', { name: '식 세우기' }).click();
await shooter.page.waitForTimeout(500);
await shooter.page.keyboard.type('0.01x', { delay: 20 });
await shooter.page.keyboard.press('Enter');
await shooter.page.waitForTimeout(400);
await shooter.page.getByRole('button', { name: '발사' }).click();
await other.page.waitForTimeout(1500);
await other.page.screenshot({ path: `${process.env.HOME}/dorms-world/.shots/mp-other-sees-shot.png` });
await shooter.page.waitForTimeout(6000);
console.log('after shot A dock:', await who(A.page));
console.log('after shot B dock:', await who(B.page));
await A.page.screenshot({ path: `${process.env.HOME}/dorms-world/.shots/mp-after-A.png` });
console.log('errors A', A.errs.slice(0, 3), 'B', B.errs.slice(0, 3));
await browser.close();
